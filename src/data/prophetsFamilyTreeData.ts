export type TreeLineageGroup =
  | 'early'
  | 'abrahamic'
  | 'ishmaelite'
  | 'israelite'
  | 'other_prophets'
  | 'ancestor_family';

export interface ProphetTreeNode {
  id: string;
  /** Matches `id` in PROPHETS_25_DATABASE when this node is one of the 25 Quranic Prophets */
  prophetId?: string;
  /** Quranic / chronological order badge (1-25) if one of the 25 Prophets */
  rank?: number;
  nameBn: string;
  nameEn: string;
  nameAr: string;
  roleBn: string;
  roleEn: string;
  eraOrRegionBn: string;
  eraOrRegionEn: string;
  lineage: TreeLineageGroup;
  isProphet25: boolean;
  /** Confirmed or strongly attested Prophet in Hadith / Quranic allusion outside the 25 */
  isHadithProphet?: boolean;
  isUlulAzm?: boolean;
  scriptureBn?: string;
  scriptureEn?: string;
  quranMentions?: number;
  /** Logical canvas coordinates inside 1140 x 1860 viewBox */
  x: number;
  y: number;
  /** 'lg' for Prophets, 'sm' for ancestors / family links */
  size: 'lg' | 'sm';
  /** Short note shown in the inspector drawer */
  noteBn: string;
  noteEn: string;
}

export interface ProphetTreeEdge {
  id: string;
  from: string;
  to: string;
  /** 'direct' = solid line, 'descent' = dashed multi-generation line, 'kinship' = dotted spouse/cousin/successor */
  kind: 'direct' | 'descent' | 'kinship';
  labelBn?: string;
  labelEn?: string;
  lineage: TreeLineageGroup;
}

export interface OtherQuranicFigure {
  id: string;
  nameBn: string;
  nameEn: string;
  nameAr: string;
  identificationBn: string;
  identificationEn: string;
  category: 'righteous' | 'family' | 'angel' | 'historical' | 'opponent';
  refBn: string;
  refEn: string;
}

