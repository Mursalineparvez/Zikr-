export function translateChapterNameBn(englishTitle: string, fallbackNumber?: string | number): string {
  const clean = (englishTitle || '').trim();
  if (!clean) {
    return fallbackNumber !== undefined ? `অধ্যায় ${fallbackNumber}` : 'মূল অধ্যায়';
  }
  const lower = clean.toLowerCase();
  if (CHAPTER_TITLE_BN_MAP[lower]) {
    return CHAPTER_TITLE_BN_MAP[lower];
  }
  const stripped = lower
    .replace(/^chapters?\s+on\s+/i, '')
    .replace(/^the\s+book\s+of\s+/i, '')
    .replace(/^the\s+book\s+on\s+/i, '')
    .replace(/^kitab\s+/i, '')
    .trim();
  if (CHAPTER_TITLE_BN_MAP[stripped]) {
    return CHAPTER_TITLE_BN_MAP[stripped];
  }
  return clean;
}
