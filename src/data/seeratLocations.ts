/**
 * Returns the best-matching SeeratLocation for a given age (1-63)
 */
export function getLocationForAge(age: number): SeeratLocation {
  for (const loc of Object.values(SEERAT_LOCATIONS)) {
    if (loc.associatedAges.includes(age)) {
      return loc;
    }
  }
  // Default to Makkah if pre-Hijrah, or Madinah if post-Hijrah
  return age <= 53 ? SEERAT_LOCATIONS.makkah : SEERAT_LOCATIONS.madinah;
}
