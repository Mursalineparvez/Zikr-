/**
 * Converts numbers into the user's localized digits:
 * - Bengali for 'bn'
 * - Eastern Arabic-Indic for 'ar', 'ur', 'fa'
 * - Standard Latin digits for 'en', 'hi', 'id', 'tr', 'ms', 'fr', 'es', 'de', 'ru', 'sw'
 */
export function formatLocalizedNumber(num: number | string, lang: ZikrLanguage = 'bn'): string {
  const str = String(num);

  if (lang === 'bn') {
    const bnDigits = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];
    return str.replace(/\d/g, (d) => bnDigits[parseInt(d, 10)]);
  }

  if (lang === 'ar' || lang === 'ur' || lang === 'fa') {
    const arDigits = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];
    return str.replace(/\d/g, (d) => arDigits[parseInt(d, 10)]);
  }

  return str;
}

