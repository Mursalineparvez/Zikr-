// Strips Arabic diacritics / tashkeel
export function stripTashkeel(text: string): string {
  return text.replace(/[\u064B-\u065F\u0670\u06D6-\u06ED]/g, '');
}

// Extracts the primary phonetic letters from an Arabic word in reading order
export function extractWordLetters(arabicWord: string): MakhrajData[] {
  const clean = stripTashkeel(arabicWord);
  const result: MakhrajData[] = [];
  for (const char of clean) {
    if (ARABIC_LETTERS_MAKHRAJ[char]) {
      result.push(ARABIC_LETTERS_MAKHRAJ[char]);
    }
  }
  return result;
}

// Returns the primary/first articulated letter and full details for an Arabic word
export function getWordMakhrajInfo(arabicWord: string): {
  primaryLetter: MakhrajData | null;
  allLetters: MakhrajData[];
  cleanText: string;
} {
  const allLetters = extractWordLetters(arabicWord);
  // Pick the first significant consonant (skip initial silent alif in 'al-' if multiple letters exist)
  let primaryLetter: MakhrajData | null = allLetters[0] || null;
  if (allLetters.length > 1 && (allLetters[0].letter === 'ا' || allLetters[0].letter === 'أ') && allLetters[1].letter === 'ل' && allLetters[2]) {
    primaryLetter = allLetters[2];
  } else if (allLetters.length > 1 && allLetters[0].letter === 'ا' && allLetters[1]) {
    primaryLetter = allLetters[1];
  }

  return {
    primaryLetter,
    allLetters,
    cleanText: stripTashkeel(arabicWord),
  };
}
